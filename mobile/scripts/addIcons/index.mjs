import { createWriteStream } from "node:fs";
import {
  access,
  copyFile,
  cp,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import { x as extract } from "tar";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const defaultMobileRoot = path.resolve(scriptDirectory, "../..");
const variants = ["filled", "outline"];
const archiveUrl = "https://codeload.github.com/tabler/tabler-icons/tar.gz/refs/heads/main";

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

export function iconIdentifier(name, variant) {
  const pascalName = name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return `TIcon${pascalName}${variant === "outline" ? "Outline" : ""}`;
}

export async function ensureCache(cacheDirectory) {
  const complete = path.join(cacheDirectory, ".complete");
  if (
    (await exists(complete)) &&
    (await Promise.all(variants.map((v) => exists(path.join(cacheDirectory, v))))).every(Boolean)
  ) {
    return;
  }

  await mkdir(cacheDirectory, { recursive: true });
  const staging = await mkdtemp(path.join(cacheDirectory, ".download-"));
  try {
    console.log("Downloading Tabler icons from GitHub...");
    const response = await fetch(archiveUrl, {
      signal: AbortSignal.timeout(180_000),
    });
    if (!response.ok || !response.body) {
      throw new Error(`Tabler download failed: HTTP ${response.status}`);
    }
    const archive = path.join(staging, "tabler.tar.gz");
    await pipeline(Readable.fromWeb(response.body), createWriteStream(archive));
    await extract({
      file: archive,
      cwd: staging,
      strip: 1,
      filter: (entryPath, entry) =>
        entry.type === "File" &&
        /^[^/]+\/(?:icons\/(?:filled|outline)\/[a-z0-9-]+\.svg|LICENSE)$/.test(entryPath),
    });
    for (const variant of variants) {
      const source = path.join(staging, "icons", variant);
      if (!(await exists(source))) {
        throw new Error(`Tabler archive is missing the ${variant} folder.`);
      }
    }
    for (const variant of variants) {
      await cp(path.join(staging, "icons", variant), path.join(cacheDirectory, variant), {
        recursive: true,
      });
    }
    await copyFile(path.join(staging, "LICENSE"), path.join(cacheDirectory, "LICENSE"));
    await writeFile(complete, `${archiveUrl}\n`);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

async function collectIcons(assetDirectory) {
  const entries = [];
  for (const variant of variants) {
    const directory = path.join(assetDirectory, variant);
    if (!(await exists(directory))) continue;
    for (const file of await readdir(directory)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.svg$/.test(file)) continue;
      const name = file.slice(0, -4);
      entries.push({
        identifier: iconIdentifier(name, variant),
        source: `@/assets/tabler/${variant}/${file}`,
      });
    }
  }
  entries.sort((a, b) => (a.identifier < b.identifier ? -1 : a.identifier > b.identifier ? 1 : 0));
  const identifiers = new Set();
  for (const { identifier } of entries) {
    if (identifiers.has(identifier)) {
      throw new Error(`Icon identifier collision: ${identifier}`);
    }
    identifiers.add(identifier);
  }
  return entries;
}

export async function generateIconsMap(assetDirectory) {
  const entries = await collectIcons(assetDirectory);
  return format(
    `// Generated by npm run addItems. Do not edit manually.
import type { ComponentType } from "react";
import { createAnimatedComponent } from "react-native-reanimated";
import type { SvgProps } from "react-native-svg";
${entries.map(({ identifier, source }) => `import ${identifier} from "${source}";`).join("\n")}

const tabler = {
${entries.map(({ identifier }) => `  ${identifier},`).join("\n")}
};

const iconsMap = { ...tabler };

const animateIcon = (icon: ComponentType<SvgProps>) => createAnimatedComponent(icon);

type AnimatedIcon = ReturnType<typeof animateIcon>;
type AnimatedIcons = {
  [Key in keyof typeof iconsMap]: AnimatedIcon;
};

export const icons = Object.entries(iconsMap).reduce<Record<string, AnimatedIcon>>(
  (result, [key, icon]) => {
    result[key] = animateIcon(icon);
    return result;
  },
  {},
) as AnimatedIcons;
`,
    {
      ...(await resolveConfig(path.join(defaultMobileRoot, "src/app/assets/icons/iconsMap.ts"))),
      parser: "typescript",
    },
  );
}

export async function addIcons(
  names,
  {
    variant = "filled",
    mobileRoot = defaultMobileRoot,
    cacheDirectory = path.join(scriptDirectory, "icons"),
  } = {},
) {
  if (!variants.includes(variant)) throw new Error(`Unknown variant: ${variant}`);
  if (!names.length) throw new Error("Provide at least one icon name.");
  for (const name of names) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
      throw new Error(`Invalid icon name: ${name}`);
    }
  }

  await ensureCache(cacheDirectory);
  const uniqueNames = [...new Set(names)];
  const missing = [];
  for (const name of uniqueNames) {
    if (!(await exists(path.join(cacheDirectory, variant, `${name}.svg`)))) {
      missing.push(name);
    }
  }
  if (missing.length) {
    throw new Error(
      `No ${variant} icons found for: ${missing.join(", ")}. Check the names or try ${variant === "filled" ? "--outline" : "--filled"}.`,
    );
  }

  const assets = path.join(mobileRoot, "src/assets/tabler");
  // Validate identifier collisions before copying anything.
  const existing = await collectIcons(assets);
  for (const name of uniqueNames) {
    const identifier = iconIdentifier(name, variant);
    const source = `@/assets/tabler/${variant}/${name}.svg`;
    if (existing.some((icon) => icon.identifier === identifier && icon.source !== source)) {
      throw new Error(`Icon identifier collision: ${identifier}`);
    }
  }
  const requestedIdentifiers = uniqueNames.map((name) => iconIdentifier(name, variant));
  if (new Set(requestedIdentifiers).size !== requestedIdentifiers.length) {
    throw new Error("Requested icon names produce duplicate identifiers.");
  }
  await mkdir(path.join(assets, variant), { recursive: true });
  for (const name of uniqueNames) {
    await copyFile(
      path.join(cacheDirectory, variant, `${name}.svg`),
      path.join(assets, variant, `${name}.svg`),
    );
  }
  await copyFile(path.join(cacheDirectory, "LICENSE"), path.join(assets, "LICENSE"));
  const mapPath = path.join(mobileRoot, "src/app/assets/icons/iconsMap.ts");
  await mkdir(path.dirname(mapPath), { recursive: true });
  const content = await generateIconsMap(assets);
  if (!(await exists(mapPath)) || (await readFile(mapPath, "utf8")) !== content) {
    await writeFile(mapPath, content);
  }
  console.log(`Added ${uniqueNames.length} ${variant} icon(s).`);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.includes("--help")) {
    console.log("Usage: npm run addItems -- [--outline|--filled] icon-name [...icon-name]");
  } else {
    const flags = args.filter((argument) => argument.startsWith("--"));
    const unknown = flags.filter((flag) => !["--outline", "--filled"].includes(flag));
    try {
      if (unknown.length) throw new Error(`Unknown option: ${unknown.join(", ")}`);
      if (flags.includes("--outline") && flags.includes("--filled")) {
        throw new Error("Choose either --outline or --filled, not both.");
      }
      await addIcons(
        args.filter((argument) => !argument.startsWith("--")),
        {
          variant: flags.includes("--outline") ? "outline" : "filled",
        },
      );
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
